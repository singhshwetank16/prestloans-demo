window.openPolicyModal = function(policyKey) {
  const modalBackdrop = document.getElementById('policy-modal');
  const modalTitle = document.getElementById('policy-modal-title');
  const modalDate = document.getElementById('policy-modal-date');
  const modalBody = document.getElementById('policy-modal-body');

  const policy = window.PREST_POLICIES[policyKey];
  if (!policy || !modalBackdrop) return;

  if (modalTitle) modalTitle.textContent = policy.title;
  if (modalDate) modalDate.textContent = `Last Updated: ${policy.lastUpdated} | RBI Compliance Version`;
  if (modalBody) modalBody.innerHTML = `<div class="policy-doc">${policy.content}</div>`;

  modalBackdrop.classList.add('active');
  document.body.style.overflow = 'hidden';
};

window.closePolicyModal = function() {
  const modalBackdrop = document.getElementById('policy-modal');
  if (modalBackdrop) {
    modalBackdrop.classList.remove('active');
    document.body.style.overflow = '';
  }
};
